const MAP = {};
EURO.split(' ').forEach((c) => { MAP[c] = 'EUR'; });
OTHER.split(' ').forEach((p) => { const [c, m] = p.split(':'); MAP[c] = m; });

module.exports = (req, res) => {
  const c = String(req.headers['x-vercel-ip-country'] || '').toUpperCase();
  res.setHeader('Cache-Control', 'private, no-store');
  res.status(200).json({ country: c || null, currency: MAP[c] || null });
};
